"""Where interview videos live.

Chunks are always appended to a file on the server's disk while an interview is running (appending to a blob in
small pieces is slow and costly). When a piece is finished it is remuxed with ffmpeg so it can be scrubbed, then:
  - with C2H_AZURE_STORAGE_CONNECTION_STRING set: uploaded to a private Azure Blob container and removed from disk.
    Playback uses a short-lived read-only link (SAS), so the video never goes through the app server again.
  - without it: kept on disk under UPLOAD_DIR/recordings and streamed by the app with range requests.
"""
import os
import shutil
import subprocess
from datetime import datetime, timedelta, timezone

from flask import current_app

LINK_MINUTES = 15


def folder():
    f = os.path.join(current_app.config["UPLOAD_DIR"], "recordings")
    os.makedirs(f, exist_ok=True)
    return f


def local_path(key):
    # keys are generated by us ("att12-interviewer-k3x9-raw.webm"); never trust a path from outside
    return os.path.join(folder(), os.path.basename(key))


def azure_conn():
    return current_app.config.get("AZURE_STORAGE_CONNECTION_STRING") or ""


def _container():
    from azure.storage.blob import BlobServiceClient
    svc = BlobServiceClient.from_connection_string(azure_conn())
    c = svc.get_container_client(current_app.config.get("AZURE_RECORDINGS_CONTAINER") or "recordings")
    try:
        c.create_container()  # private by default
    except Exception:  # noqa: BLE001 - already exists
        pass
    return svc, c


def append(key, data):
    with open(local_path(key), "ab") as fh:
        fh.write(data)
        return fh.tell()


def ffmpeg():
    return shutil.which(current_app.config.get("FFMPEG_BIN") or "ffmpeg")


def finish(raw_key, mime):
    """Remux the raw chunk stream into a file with a proper index (duration, seek points).
    Returns (file_key, seconds, note). Falls back to the raw file if ffmpeg is missing or fails."""
    src = local_path(raw_key)
    if not os.path.exists(src) or os.path.getsize(src) == 0:
        return None, 0, "No video was received."
    ext = "mp4" if "mp4" in (mime or "") else "webm"
    out_key = raw_key.replace("-raw.", "-final.").rsplit(".", 1)[0] + "." + ext
    dst = local_path(out_key)
    bin_ = ffmpeg()
    note = None
    if bin_:
        args = [bin_, "-y", "-loglevel", "error", "-fflags", "+genpts", "-i", src, "-c", "copy"]
        if ext == "mp4":
            args += ["-movflags", "+faststart"]
        try:
            subprocess.run(args + [dst], check=True, timeout=1800, capture_output=True)
        except (subprocess.SubprocessError, OSError) as e:
            note = "Saved without the seek index (ffmpeg failed)."
            current_app.logger.warning("ffmpeg remux failed for %s: %s", raw_key, e)
            shutil.copyfile(src, dst)
    else:
        note = "Saved without the seek index (ffmpeg is not installed on the server)."
        shutil.copyfile(src, dst)
    seconds = probe_seconds(dst)
    os.remove(src)
    return out_key, seconds, note


def probe_seconds(path):
    bin_ = ffmpeg()
    if not bin_:
        return None
    probe = os.path.join(os.path.dirname(bin_), "ffprobe")
    if not os.path.exists(probe):
        probe = shutil.which("ffprobe")
    if not probe:
        return None
    try:
        r = subprocess.run([probe, "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", path],
                           capture_output=True, text=True, timeout=120)
        return round(float(r.stdout.strip()), 1)
    except (ValueError, subprocess.SubprocessError, OSError):
        return None


def store(file_key, mime):
    """Move a finished file to Azure when configured. Returns 'azure' or 'local'."""
    if not azure_conn():
        return "local"
    from azure.storage.blob import ContentSettings
    _, c = _container()
    with open(local_path(file_key), "rb") as fh:
        c.upload_blob(file_key, fh, overwrite=True, content_settings=ContentSettings(content_type=mime))
    os.remove(local_path(file_key))
    return "azure"


def link(rec, download=False):
    """A short-lived read link for a video stored in Azure."""
    from azure.storage.blob import BlobSasPermissions, generate_blob_sas
    svc, c = _container()
    cred = svc.credential
    exp = datetime.now(timezone.utc) + timedelta(minutes=LINK_MINUTES)
    sas = generate_blob_sas(account_name=svc.account_name, container_name=c.container_name, blob_name=rec.file_key,
                            account_key=getattr(cred, "account_key", None), permission=BlobSasPermissions(read=True), expiry=exp,
                            content_disposition=f'attachment; filename="interview-{rec.attempt_id}-{rec.id}.{rec.file_key.rsplit(".", 1)[-1]}"' if download else None)
    return f"{c.url}/{rec.file_key}?{sas}"


def delete(rec):
    for key in (rec.raw_key, rec.file_key):
        if not key:
            continue
        p = local_path(key)
        if os.path.exists(p):
            os.remove(p)
    if rec.storage == "azure" and rec.file_key and azure_conn():
        try:
            _, c = _container()
            c.delete_blob(rec.file_key)
        except Exception as e:  # noqa: BLE001 - already gone
            current_app.logger.info("blob delete %s: %s", rec.file_key, e)
